"""Pawn Forever's stat weights -> ForeverQoLPanel/WeightData.lua (the loot optimizer's default weights).

Usage: python tools/pawn_weights.py               (downloads Weights.lua and LICENSE from GitHub)
       python tools/pawn_weights.py Weights.lua LICENSE
Source: https://github.com/turlockmike/pawn-forever (MIT). Its license text is copied into the data file, which ships
with the addon.
"""
import re, sys, pathlib, urllib.request
here = pathlib.Path(__file__).parent
BASE = "https://raw.githubusercontent.com/turlockmike/pawn-forever/main/"

def get(i, path):
    if len(sys.argv) > i:
        return pathlib.Path(sys.argv[i]).read_text(encoding="utf-8")
    req = urllib.request.Request(BASE + path, headers={"User-Agent": "Mozilla/5.0"})
    return urllib.request.urlopen(req, timeout=30).read().decode("utf-8")

src = get(1, "PawnForever/Weights.lua")
lic = get(2, "LICENSE").strip()

entry = re.compile(r'\{ class = "(\w+)", classID = \d+, key = "(\w+)", specID = (\w+), label = "([^"]+)",\s*'
                   r'leveling = \{([^}]*)\},\s*max = \{([^}]*)\} \}', re.S)
def table(body):
    return {k: float(v) for k, v in re.findall(r"(\w+) = ([\d.]+)", body)}

classes = {}
for cls, key, spec, label, lev, mx in entry.findall(src):
    c = classes.setdefault(cls, [])
    c.append({"key": key, "spec": None if spec == "nil" else int(spec),
              "label": re.sub(r"\s*Forever$", "", label), "leveling": table(lev), "max": table(mx)})

# talent tab (game order) -> profile: by spec id; druid tabs are balance, feral, restoration (bear is an extra profile)
TABS = {"DRUID": ["balance", "feral", "restoration"]}
def tabs(cls, profiles):
    if cls in TABS:
        return TABS[cls]
    by = {p["spec"]: p["key"] for p in profiles if p["spec"]}
    return [by[i] for i in sorted(by)]

def num(v):
    s = ("%.4f" % v).rstrip("0").rstrip(".")
    return s or "0"
def lua_table(d):
    return "{ " + ", ".join(f"{k} = {num(v)}" for k, v in sorted(d.items())) + " }"

out = ["local _, ns = ...", "",
       "-- Stat weights per class and talent tree for WoW: Forever, one set for levelling and one for the highest level.",
       "-- From Pawn Forever (https://github.com/turlockmike/pawn-forever), generated by tools/pawn_weights.py.",
       "-- Weights are Pawn's stat names; chances (crit, hit, haste, dodge, parry, block, expertise) are per 1 %.",
       "--[[ Pawn Forever's license:", "", lic, "]]", "",
       "ns.WeightData = {"]
total = 0
for cls in sorted(classes):
    profiles = classes[cls]
    out.append(f'    {cls} = {{')
    out.append("        tabs = { " + ", ".join(f'"{k}"' for k in tabs(cls, profiles)) + " },")
    out.append("        profiles = {")
    for p in profiles:
        out.append(f'            {p["key"]} = {{ label = "{p["label"]}", tab = {p["spec"] if p["spec"] else "nil"},')
        out.append(f'                leveling = {lua_table(p["leveling"])},')
        out.append(f'                max = {lua_table(p["max"])} }},')
        total += 1
    out.append("        },")
    out.append("        order = { " + ", ".join(f'"{p["key"]}"' for p in profiles) + " },")
    out.append("    },")
out += ["}", ""]
target = here.parent / "ForeverQoLPanel" / "WeightData.lua"
target.write_text("\n".join(out), encoding="utf-8")
keys = sorted({k for ps in classes.values() for p in ps for k in list(p["leveling"]) + list(p["max"])})
print(len(classes), "classes,", total, "profiles; stat names:", ", ".join(keys))
print("written", target, target.stat().st_size, "bytes")
